import { readdirSync, readFileSync, writeFileSync, copyFileSync, mkdirSync } from 'node:fs';
import { join } from 'node:path';

// Vendor only the official Ionicons SVGs used by the app. Web icons must work
// without a font request, including on a cold cache or a slow connection.
const glyphs = JSON.parse(
  readFileSync(
    'node_modules/@expo/vector-icons/build/vendor/react-native-vector-icons/glyphmaps/Ionicons.json',
    'utf8',
  ),
);
function sources(dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const path = join(dir, entry.name);
    return entry.isDirectory()
      ? sources(path)
      : /\.tsx?$/.test(path) && !path.endsWith('webIcons.ts')
        ? [path]
        : [];
  });
}
const names = new Set(['help-circle-outline']);
for (const path of ['App.tsx', ...sources('src')]) {
  for (const [, name] of readFileSync(path, 'utf8').matchAll(/['"]([a-z][a-z0-9-]*)['"]/g)) {
    if (Object.hasOwn(glyphs, name)) names.add(name);
  }
}
const icons = Object.fromEntries(
  [...names].sort().map((name) => {
    const svg = readFileSync(`node_modules/ionicons/dist/svg/${name}.svg`, 'utf8');
    const body = svg.match(/<svg\b[^>]*>([\s\S]*?)<\/svg>/)?.[1];
    if (!body) throw new Error(`Invalid SVG: ${name}`);
    return [name, body];
  }),
);
mkdirSync('src/assets', { recursive: true });
writeFileSync(
  'src/assets/webIcons.ts',
  '// Generated by scripts/generate-web-icons.mjs from ionicons@7.4.0 (MIT).\n// See ionicons.LICENSE. Do not edit by hand.\nexport const webIcons: Record<string, string> = ' +
    JSON.stringify(icons, null, 2) +
    ';\n',
);
copyFileSync('node_modules/ionicons/LICENSE', 'src/assets/ionicons.LICENSE');
console.log(`Prepared ${names.size} inline web icons; no icon font required.`);
